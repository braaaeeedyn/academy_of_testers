// One-time codegen: merges data/topicalQuestions (difficulty-tagged) and
// data/practiceProblems (untagged review sets) into data/unitBank/<slug>.ts.
// Units are merged by unitNumber (topical title wins); questions with identical
// normalized text within a unit are deduped (topical wins, keeping its tag).
// Run from web/: npx -y tsx tools/generate-unit-bank.mjs

import { writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const { TOPICAL_DATA } = await import(pathToFileURL(join(root, '../src/data/topicalQuestions/index.ts')).href)
const { AP_PRACTICE_DATA } = await import(pathToFileURL(join(root, '../src/data/practiceProblems/apPracticeQuestions.ts')).href)
const outDir = join(root, '../src/data/unitBank')

const normalize = (s) => s.replace(/\s+/g, ' ').trim().toLowerCase()

/** slug -> { label, slug, units: Map<unitNumber, {unitNumber,title,questions,seen:Set}> } */
const banks = new Map()

function bankFor(slug, label) {
  if (!banks.has(slug)) banks.set(slug, { label, slug, units: new Map() })
  return banks.get(slug)
}

function unitFor(bank, unitNumber, title) {
  if (!bank.units.has(unitNumber)) {
    bank.units.set(unitNumber, { unitNumber, title, questions: [], seen: new Set() })
  }
  return bank.units.get(unitNumber)
}

function addQuestion(unit, q, id, difficulty) {
  const key = normalize(q.question)
  if (unit.seen.has(key)) return 0
  unit.seen.add(key)
  unit.questions.push({
    id,
    question: q.question,
    options: q.options,
    correctAnswer: q.correctAnswer,
    explanation: q.explanation,
    ...(difficulty ? { difficulty } : {}),
  })
  return 1
}

// Topical first so its difficulty-tagged copy wins any dedupe collision.
for (const exam of TOPICAL_DATA) {
  const bank = bankFor(exam.slug, exam.label)
  for (const u of exam.units) {
    const unit = unitFor(bank, u.unitNumber, u.title)
    for (const d of ['easy', 'medium', 'hard']) {
      u[d].forEach((q, i) => addQuestion(unit, q, `t-${u.unitNumber}-${d}-${q.id ?? i}`, d))
    }
  }
}

let dropped = 0
for (const exam of AP_PRACTICE_DATA) {
  const bank = bankFor(exam.slug, exam.label)
  for (const u of exam.units) {
    const unit = unitFor(bank, u.unitNumber, u.title)
    u.questions.forEach((q, i) => {
      dropped += 1 - addQuestion(unit, q, `r-${u.unitNumber}-${q.id ?? i}`)
    })
  }
}

const constName = (slug) => 'BANK_' + slug.toUpperCase().replace(/-/g, '_')

const sorted = [...banks.values()].sort((a, b) => a.slug.localeCompare(b.slug))
let totalQ = 0
for (const bank of sorted) {
  const units = [...bank.units.values()]
    .sort((a, b) => a.unitNumber - b.unitNumber)
    .map(({ seen, ...u }) => u)
  totalQ += units.reduce((n, u) => n + u.questions.length, 0)
  const body = JSON.stringify({ label: bank.label, slug: bank.slug, units }, null, 2)
  const file = `import type { SubjectUnitBank } from './types'\n\nexport const ${constName(bank.slug)}: SubjectUnitBank = ${body}\n`
  writeFileSync(join(outDir, `${bank.slug}.ts`), file, 'utf8')
}

const index = [
  '// GENERATED by tools/generate-unit-bank.mjs — do not edit by hand.',
  ...sorted.map((b) => `import { ${constName(b.slug)} } from './${b.slug}'`),
  '',
  "import type { SubjectUnitBank } from './types'",
  '',
  'export const UNIT_BANKS: SubjectUnitBank[] = [',
  ...sorted.map((b) => `  ${constName(b.slug)},`),
  ']',
  '',
].join('\n')
writeFileSync(join(outDir, 'index.ts'), index, 'utf8')

console.log(`${sorted.length} subjects, ${totalQ} questions written (${dropped} duplicates dropped)`)
